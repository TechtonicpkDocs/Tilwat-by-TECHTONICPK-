private const val B64_ALPHA = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

private fun decodeB64(b64: String): ByteArray {
    val out = ByteArray((b64.length * 3) ushr 2)
    var n = 0
    var buf = 0
    var bits = 0
    for (i in b64.indices) {
        val v = B64_ALPHA.indexOf(b64[i])
        if (v < 0) continue
        buf = (buf shl 6) or v
        bits += 6
        if (bits >= 8) {
            bits -= 8
            out[n++] = ((buf shr bits) and 255).toByte()
        }
    }
    return out.copyOf(n)
}

private val waqfBits: ByteArray by lazy { decodeB64(WAQF_B64) }
private val procliticBits: ByteArray by lazy { decodeB64(PROCLITIC_B64) }

private fun bit(table: ByteArray, i: Int): Boolean {
    if (i < 0) return false
    val byte = i shr 3
    if (byte >= table.size) return false
    return ((table[byte].toInt() shr (i and 7)) and 1) == 1
}

fun waqfMarked(word: Int): Boolean = bit(waqfBits, word)

fun procliticOnset(word: Int): Boolean = bit(procliticBits, word)
